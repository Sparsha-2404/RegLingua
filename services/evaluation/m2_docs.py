def script_table(scripts: List[dict], runtimes: Dict[str, dict]) -> str:
    rows = ["| Script | Purpose | Inputs | Outputs | Runtime (measured, Linux sandbox) | Rerun vs stored outputs |", "|---|---|---|---|---|---|"]
    for s in scripts:
        rt = runtimes.get(s["script"])
        rep = "-"
        if rt is None:
            run = "not measured"
        elif rt["status"] == "skipped":
            run = f"not run: {rt['reason']}"
        elif rt["status"] == "needs_hf":
            run = f"not measurable here: {rt['reason']}"
        elif rt["status"] == "ran_exit1":
            run = f"{rt['seconds']} s (exit 1: {rt['reason']})"
            rep = (rt.get("reproduces") or "-") if s.get("outputs") else "-"
        elif rt["status"] != "ok":
            run = f"failed here (exit {rt.get('exit_code')}): {rt.get('last_line', '')[:70]}"
        else:
            run = f"{rt['seconds']} s"
            rep = (rt.get("reproduces") or "-") if s.get("outputs") else "-"
        rows.append(f"| `scripts\\{s['script']}` | {s['purpose']} | {s['inputs']} | {s['outputs'] or '(console only)'} | {run} | {rep} |")
    return "\n".join(rows)
