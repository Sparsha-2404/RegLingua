class R:
    """Formatter that records which ledger keys were used."""

    def __init__(self, ledger: Dict[str, dict]):
        self.L, self.used, self.missing = ledger, [], []

    def _v(self, key):
        if key in self.L:
            self.used.append(key)
            return self.L[key]["value"]
        self.missing.append(key)
        return None

    def i(self, k):
        v = self._v(k)
        return NA if v is None else str(int(v))

    def s(self, k):
        v = self._v(k)
        return NA if v is None else str(v)

    def p(self, k):
        v = self._v(k)
        return NA if v is None else f"{100 * v:.1f}%"

    def f(self, k):
        v = self._v(k)
        return NA if v is None else f"{v:.3f}"

    def pc(self, k):      # percentage with CI
        v, lo, hi = self._v(k), self._v(k + ".ci_low"), self._v(k + ".ci_high")
        return NA if v is None else (f"{100 * v:.1f}%" + ("" if lo is None else f" (95% CI {100 * lo:.1f}-{100 * hi:.1f}%)"))

    def fc(self, k):      # 3-decimal with CI
        v, lo, hi = self._v(k), self._v(k + ".ci_low"), self._v(k + ".ci_high")
        return NA if v is None else (f"{v:.3f}" + ("" if lo is None else f" (95% CI {lo:.3f}-{hi:.3f})"))


def sources_table(ledger: Dict[str, dict], used: List[str]) -> str:
    seen, rows = set(), []
    for k in used:
        if k in seen or k not in ledger:
            continue
        seen.add(k)
        e = ledger[k]
        rows.append(f"| `{k}` | {', '.join('`' + s + '`' for s in e['source'])} | {e['derivation']} |")
    return "| ledger key | source file | derivation |\n|---|---|---|\n" + "\n".join(rows)


